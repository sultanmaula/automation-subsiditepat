        '9436' => 'Deiyai',
        '9471' => 'Jayapura',
    ];

    /**
     * Ambil nama kab/kota dari 4 digit pertama NIK (kode provinsi + kode kab/kota).
     * Kembalikan null jika kode tidak ditemukan.
     */
    public static function getCityName(string $nik): ?string
    {
        $code = substr($nik, 0, 4);

        return self::$map[$code] ?? null;
    }
